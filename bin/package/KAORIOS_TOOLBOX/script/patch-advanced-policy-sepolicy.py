#!/usr/bin/env python3
"""Build-time SELinux policy for the kaorios_advanced_policy binder service.

Adds the smallest rule set the Kaorios Toolbox AdvancedPolicy service needs to
an extracted ROM:

  * a service type for kaorios_advanced_policy;
  * system_server permission to register (add) it;
  * the SettingsProvider domain permission to find it and to reach
    system_server over binder.

Nothing is guessed. The SettingsProvider domain is read from the ROM's own
seapp_contexts and has to be a type the ROM's policy actually declares, and the
rules are written to the split-policy partition that is really present. When
the layout cannot be recognised the module writes nothing and reports SKIP, so
an unfamiliar ROM shape cannot produce a policy that fails to compile. If the
host has secilc, the policy is compiled before and after the edit and the edit
is rolled back when the compile regresses.

Exit codes: 0 applied/verified, 1 error, 3 unsupported layout (skipped).
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

SERVICE = "kaorios_advanced_policy"
TYPE = SERVICE + "_service"
CONTEXT = f"u:object_r:{TYPE}:s0"
GENERATOR = "patch-advanced-policy-sepolicy.py"
BEGIN = f";; BEGIN {SERVICE} (generated by {GENERATOR})"
END = f";; END {SERVICE}"
DOMAIN_NOTE = ";; settings-provider-domain:"
CTX_BEGIN = f"# BEGIN {SERVICE} (generated by {GENERATOR})"
CTX_END = f"# END {SERVICE}"
IDENT = re.compile(r"[a-zA-Z_][a-zA-Z_0-9]*\Z")
SKIP_RC = 3

# Split-policy partitions in preference order. The Toolbox is installed into
# system_ext, so its policy belongs there whenever that partition carries
# policy of its own.
PARTITIONS = (
    ("system_ext", "system_ext_sepolicy.cil", "system_ext_service_contexts"),
    ("product", "product_sepolicy.cil", "product_service_contexts"),
    ("system", "plat_sepolicy.cil", "plat_service_contexts"),
)
SCAN_PARTITIONS = ("system", "system_ext", "product", "vendor", "odm")


def log(message: str) -> None:
    print(f"SEPOLICY: {message}", file=sys.stderr)


def selinux_dir(root: Path, partition: str) -> Path | None:
    """Locate a partition's etc/selinux directory in an extracted ROM."""
    if partition == "system":
        candidates = ("system/system/etc/selinux", "system/etc/selinux")
    else:
        candidates = (
            f"{partition}/etc/selinux",
            f"system/{partition}/etc/selinux",
            f"{partition}/{partition}/etc/selinux",
        )
    for rel in candidates:
        path = root / rel
        if path.is_dir():
            return path
    return None


def read_text(path: Path) -> str | None:
    """Read a policy file, refusing binary blobs and undecodable content."""
    try:
        raw = path.read_bytes()
    except OSError:
        return None
    if b"\0" in raw:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeError:
        return None


def policy_sources(root: Path) -> list[str]:
    """Every readable CIL/.te policy source across the partitions present."""
    sources = []
    for partition in SCAN_PARTITIONS:
        base = selinux_dir(root, partition)
        if base is None:
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.suffix not in (".cil", ".te"):
                continue
            text = read_text(path)
            if text is not None:
                sources.append(text)
    return sources


def declares_type(sources: list[str], name: str) -> bool:
    """True when the ROM's own policy declares this type or attribute."""
    cil_type = re.compile(rf"\(\s*(?:type|typeattribute|typealias)\s+{name}\s*\)")
    cil_member = re.compile(rf"\(\s*typeattributeset\s+\w+\s+\([^()]*\b{name}\b[^()]*\)\s*\)")
    te_type = re.compile(rf"^\s*(?:type|attribute)\s+{name}\s*[,;]", re.MULTILINE)
    return any(
        cil_type.search(text) or cil_member.search(text) or te_type.search(text)
        for text in sources
    )


def seapp_candidates(root: Path) -> tuple[list[str], list[str]]:
    """SettingsProvider domains from seapp_contexts: (named, generic)."""
    named: list[str] = []
    generic: list[str] = []
    for partition in SCAN_PARTITIONS:
        base = selinux_dir(root, partition)
        if base is None:
            continue
        for path in sorted(base.rglob("*seapp_contexts")):
            text = read_text(path) if path.is_file() else None
            if text is None:
                continue
            for line in text.splitlines():
                fields = line.split("#", 1)[0].split()
                if not fields or any("=" not in field for field in fields):
                    continue
                entry = dict(field.split("=", 1) for field in fields)
                domain = entry.get("domain")
                if (
                    domain is None
                    or entry.get("user") != "system"
                    or entry.get("seinfo") != "platform"
                    # SettingsProvider is a signed platform priv-app running in
                    # the system UID, so rules scoped to anything else cannot
                    # describe it.
                    or entry.get("isPrivApp", "true").lower() == "false"
                    or entry.get("isSystemServer", "false").lower() == "true"
                    or entry.get("isEphemeralApp", "false").lower() == "true"
                    or entry.get("fromRunAs", "false").lower() == "true"
                    or not IDENT.match(domain)
                ):
                    continue
                name = entry.get("name")
                if name is None:
                    if domain not in generic:
                        generic.append(domain)
                elif name.rstrip("*") and "com.android.providers.settings".startswith(
                    name.rstrip("*")
                ):
                    if domain not in named:
                        named.append(domain)
    return named, generic


def resolve_domain(sources: list[str], named: list[str], generic: list[str]) -> str | None:
    """Pick one SettingsProvider domain the ROM's policy really declares."""
    for group in (named, generic):
        declared = [domain for domain in group if declares_type(sources, domain)]
        if len(declared) == 1:
            return declared[0]
        if len(declared) > 1:
            # Several platform-app rules exist; only the documented
            # SettingsProvider domain is safe to assume.
            return "system_app" if "system_app" in declared else None
    return None


def policy_block(domain: str) -> str:
    """The minimal CIL rules for the AdvancedPolicy service."""
    return "\n".join(
        (
            "",
            BEGIN,
            f"{DOMAIN_NOTE} {domain}",
            f"(type {TYPE})",
            f"(roletype object_r {TYPE})",
            f"(typeattributeset service_manager_type ({TYPE}))",
            f"(allow system_server {TYPE} (service_manager (add)))",
            f"(allow {domain} {TYPE} (service_manager (find)))",
            f"(allow {domain} system_server (binder (call)))",
            END,
            "",
        )
    )


def context_block() -> str:
    return "\n".join(("", CTX_BEGIN, f"{SERVICE} {CONTEXT}", CTX_END, ""))


def balanced(text: str) -> bool:
    """Cheap CIL sanity check: every parenthesis is closed, none extra."""
    depth = 0
    for line in text.splitlines():
        for char in line.split(";", 1)[0]:
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
                if depth < 0:
                    return False
    return depth == 0


def existing_domain(text: str) -> str | None:
    """The domain recorded in a block this script wrote earlier."""
    match = re.search(rf"^{re.escape(DOMAIN_NOTE)}\s*(\w+)\s*$", text, re.MULTILINE)
    return match.group(1) if match else None


def strip_block(text: str, begin: str, end: str) -> str:
    """Remove a previously generated block so the edit stays idempotent."""
    pattern = re.compile(
        rf"\n?{re.escape(begin)}.*?{re.escape(end)}[^\n]*\n?", re.DOTALL
    )
    return pattern.sub("\n", text)


def compile_inputs(root: Path) -> list[Path] | None:
    """The CIL files init would load, in load order, if they can be found."""
    plat = selinux_dir(root, "system")
    if plat is None:
        return None
    files = [plat / "plat_sepolicy.cil"]
    if not files[0].is_file():
        return None

    # The mapping file is chosen by the vendor's target platform version.
    version = None
    for partition in ("vendor", "odm"):
        base = selinux_dir(root, partition)
        if base is None:
            continue
        vers = base / "plat_sepolicy_vers.txt"
        if vers.is_file():
            text = read_text(vers)
            if text and text.strip():
                version = text.strip()
                break
    for partition, name in (("system", "mapping"), ("system_ext", "mapping")):
        base = selinux_dir(root, partition)
        if base is None:
            continue
        mapping = base / name
        if not mapping.is_dir():
            continue
        chosen = mapping / f"{version}.cil" if version else None
        if chosen is not None and chosen.is_file():
            files.append(chosen)
        else:
            # No vendor version pin: take the newest mapping available.
            available = sorted(
                (path for path in mapping.glob("*.cil") if path.is_file()),
                key=lambda path: path.name,
            )
            if available:
                files.append(available[-1])

    for partition, cil, _ in PARTITIONS:
        if partition == "system":
            continue
        base = selinux_dir(root, partition)
        if base is not None and (base / cil).is_file():
            files.append(base / cil)
    for partition, cil in (("vendor", "vendor_sepolicy.cil"), ("odm", "odm_sepolicy.cil")):
        base = selinux_dir(root, partition)
        if base is not None and (base / cil).is_file():
            files.append(base / cil)
    return files


def try_compile(files: list[Path], neverallow: bool) -> bool:
    """Compile the policy set with secilc; True when it builds cleanly."""
    with tempfile.TemporaryDirectory() as tmp:
        command = ["secilc", "-m", "-M", "true", "-G", "-c", "30",
                   "-o", str(Path(tmp) / "policy"), "-f", "/dev/null"]
        if not neverallow:
            command.insert(1, "-N")
        try:
            result = subprocess.run(
                command + [str(path) for path in files],
                capture_output=True, text=True, timeout=600,
            )
        except (OSError, subprocess.SubprocessError):
            return False
        return result.returncode == 0


def compile_mode(files: list[Path]) -> bool | None:
    """Establish a baseline: returns the neverallow mode that builds, or None."""
    for neverallow in (True, False):
        if try_compile(files, neverallow):
            return neverallow
    return None


def write_atomic(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".kaorios.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def target_partition(root: Path) -> tuple[str, Path, Path] | None:
    """The partition whose policy this edit belongs in."""
    for partition, cil, contexts in PARTITIONS:
        base = selinux_dir(root, partition)
        if base is None:
            continue
        cil_path = base / cil
        if cil_path.is_file() and read_text(cil_path) is not None:
            return partition, cil_path, base / contexts
    return None


def applied_partition(root: Path) -> tuple[str, Path, Path] | None:
    """The partition already carrying a block this script wrote."""
    for partition, cil, contexts in PARTITIONS:
        base = selinux_dir(root, partition)
        if base is None:
            continue
        text = read_text(base / cil) if (base / cil).is_file() else None
        if text is not None and BEGIN in text:
            return partition, base / cil, base / contexts
    return None


def verify(root: Path, checker: Path) -> int:
    """Confirm the deployed policy using the upstream read-only checker."""
    applied = applied_partition(root)
    if applied is None:
        log("verification failed: no generated policy block found")
        return 1
    partition, cil_path, _ = applied
    domain = existing_domain(read_text(cil_path) or "")
    if domain is None:
        log("verification failed: generated block has no recorded domain")
        return 1
    command = [sys.executable, str(checker), "--root", str(cil_path.parent),
               "--settings-domain", domain]
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=600)
    except (OSError, subprocess.SubprocessError) as error:
        log(f"verification failed: could not run checker ({error})")
        return 1
    report = dict(
        (key.strip(), value.strip())
        for key, _, value in (line.partition("=") for line in result.stdout.splitlines())
        if key.strip()
    )
    print(result.stdout, end="")
    required = ("POLICY_TYPE_DEFINED", "SYSTEM_SERVER_ADD_ALLOWED",
                "SETTINGS_DOMAIN_FIND_ALLOWED", "BINDER_CALL_PATH_ALLOWED")
    missing = [key for key in required if report.get(key) != "YES"]
    if report.get("SERVICE_CONTEXT_MAPPING") != "FOUND" or missing:
        log(f"verification failed in {partition}: {', '.join(missing) or 'service context mapping'}")
        return 1
    log(f"verified {SERVICE} policy in {partition} for domain {domain}")
    return 0


def apply(root: Path, override: str | None) -> int:
    target = target_partition(root)
    if target is None:
        log("skipped: no writable split-policy CIL found in this ROM")
        return SKIP_RC
    partition, cil_path, ctx_path = target

    sources = policy_sources(root)
    if not sources:
        log("skipped: no readable policy sources found")
        return SKIP_RC
    for required in ("system_server", "service_manager_type"):
        if not declares_type(sources, required):
            log(f"skipped: ROM policy does not declare {required}")
            return SKIP_RC

    if override is not None:
        if not declares_type(sources, override):
            log(f"error: requested domain {override} is not declared by this ROM")
            return 1
        domain = override
        log(f"using caller-supplied SettingsProvider domain {domain}")
    else:
        named, generic = seapp_candidates(root)
        domain = resolve_domain(sources, named, generic)
        if domain is None:
            log("skipped: could not determine the SettingsProvider SELinux domain "
                "from seapp_contexts")
            return SKIP_RC
        log(f"resolved SettingsProvider domain {domain} from seapp_contexts")

    cil_before = read_text(cil_path)
    ctx_before = read_text(ctx_path) if ctx_path.is_file() else ""
    if cil_before is None or ctx_before is None:
        log("skipped: policy files are not readable text")
        return SKIP_RC

    cil_clean = strip_block(cil_before, BEGIN, END)
    ctx_clean = strip_block(ctx_before, CTX_BEGIN, CTX_END)
    if re.search(rf"\b{TYPE}\b", cil_clean) or any(
        re.search(rf"\b{TYPE}\b", text)
        for text in policy_sources(root)
        if BEGIN not in text
    ):
        log(f"skipped: {TYPE} is already defined by this ROM outside the generated block")
        return SKIP_RC

    cil_after = cil_clean.rstrip("\n") + "\n" + policy_block(domain)
    ctx_after = ctx_clean.rstrip("\n") + "\n" + context_block()
    if ctx_clean.strip() == "":
        ctx_after = context_block().lstrip("\n")
    if balanced(cil_clean) and not balanced(cil_after):
        log("error: generated policy is not parenthesis-balanced; refusing to write")
        return 1

    if cil_before == cil_after and ctx_before == ctx_after:
        log(f"{SERVICE} policy already present in {partition}; nothing to do")
        return 0

    inputs = compile_inputs(root)
    baseline: bool | None = None
    if inputs is not None:
        baseline = compile_mode(inputs)
        if baseline is None:
            log("note: policy does not compile before the edit; skipping compile check")
    else:
        log("note: secilc inputs incomplete; skipping compile check")

    write_atomic(cil_path, cil_after)
    write_atomic(ctx_path, ctx_after)

    if inputs is not None and baseline is not None and not try_compile(inputs, baseline):
        write_atomic(cil_path, cil_before)
        if ctx_before.strip() == "" and not ctx_path.exists():
            ctx_path.unlink(missing_ok=True)
        else:
            write_atomic(ctx_path, ctx_before)
        log("error: policy failed to compile with the new rules; rolled back")
        return 1
    if inputs is not None and baseline is not None:
        log("policy compiles with the new rules (secilc)")

    log(f"applied {SERVICE} policy to {partition} for domain {domain}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path, help="extracted ROM image root")
    parser.add_argument("--settings-domain", help="override the SettingsProvider domain")
    parser.add_argument("--strict", action="store_true",
                        help="treat an unsupported layout as a failure")
    parser.add_argument("--verify-only", action="store_true",
                        help="check an already patched ROM and write nothing")
    args = parser.parse_args()

    if not args.root.is_dir():
        log(f"error: root is not a directory: {args.root}")
        return 1
    if args.settings_domain is not None and not IDENT.match(args.settings_domain):
        parser.error("invalid SettingsProvider domain")

    checker = Path(__file__).resolve().parent / "check-advanced-policy-sepolicy.py"
    if args.verify_only:
        if not checker.is_file():
            log("error: upstream checker is missing")
            return 1
        return verify(args.root, checker)

    rc = apply(args.root, args.settings_domain)
    if rc == SKIP_RC and args.strict:
        log("error: --strict requested and the policy could not be applied")
        return 1
    if rc == 0 and checker.is_file():
        return verify(args.root, checker)
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
